const PER_ID = new Map(PERSONAGGI.map((p) => [p.id, p]));

/** Trova un personaggio dal suo id; errore se non esiste. */
export function personaggio(id: string): Personaggio {
  const p = PER_ID.get(id);
  if (!p) throw new Error(`Personaggio sconosciuto: ${id}`);
  return p;
}
